def get_condition_by_sum(S):
    """Получение условий эксплуатации по сумме S"""
    if 1 <= S <= 2:
        return CONDITIONS[1]
    elif 3 <= S <= 4:
        return CONDITIONS[3]
    elif 5 <= S <= 6:
        return CONDITIONS[5]
    elif 7 <= S <= 8:
        return CONDITIONS[7]
    elif 9 <= S <= 11:
        return CONDITIONS[9]
    else:
        return CONDITIONS[1]


def get_lambda_base(element_key, col_index):
    """Получение базовой интенсивности отказов для элемента с учетом столбца"""
    if element_key in LAMBDA_BASE:
        values = LAMBDA_BASE[element_key]
        if col_index < len(values):
            return values[col_index]
    return 0.001


def get_a5_value(element_type, temperature, kn=0.5):
    """Получение коэффициента a5 для элемента"""
    if element_type not in A5_TABLE:
        return 1.0

    table = A5_TABLE[element_type]
    temps = sorted(table.keys())
    temp = min(temps, key=lambda x: abs(x - temperature))

    if temperature > max(temps):
        temp = max(temps)

    kn_values = sorted(table[temp].keys())
    kn_val = min(kn_values, key=lambda x: abs(x - kn))

    return table[temp][kn_val]


